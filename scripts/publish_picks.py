"""Copy picked takes into public/ for Remotion and write config/picks_manifest.json (what exists under public/).

Stills: config/stills.json "kept" {item: seed} -> public/media/picks/<item>.png. Clips: config/clips.json "kept"
{clip: path} -> public/media/picks/<clip>.mp4 (once batch 2 exists). The manifest also lists the chat capture.
src/Main.tsx renders a labelled placeholder for anything not in the manifest.
Usage: <venv>/bin/python -I scripts/publish_picks.py   (needs Pillow)
"""
import json
import shutil
from pathlib import Path

PUB = Path("public")
dst = PUB / "media/picks"; dst.mkdir(parents=True, exist_ok=True)
for item, k in json.load(open("config/stills.json")).get("kept", {}).items():
    src = Path(f"takes/stills/{item}/{k if isinstance(k, str) else f'{item}_s{k}'}.png")   # seed, or a file stem
    if src.exists():
        shutil.copy2(src, dst / f"{item}.png")
clips = Path("config/clips.json")
if clips.exists():
    for clip, path in json.load(open(clips)).get("kept", {}).items():
        if Path(path).exists():
            shutil.copy2(path, dst / f"{clip}.mp4")
files = sorted(str(p.relative_to(PUB)) for p in (PUB / "media").rglob("*") if p.is_file() and "test" not in p.parts)
from PIL import Image
sizes = {f: list(Image.open(PUB / f).size) for f in files if f.endswith(".png")}
json.dump({"_doc": "Generated by scripts/publish_picks.py: media present under public/, with image sizes.", "files": files, "sizes": sizes},
          open("config/picks_manifest.json", "w"), indent=1)
print(len(files), "files:", files)
